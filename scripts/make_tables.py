"""Build LaTeX result macros and table bodies from manifests (never by hand).

    python scripts/make_tables.py [--manifest-root results/manifests] [--out paper/generated] [--citable]

Every macro is always defined; results not yet produced render as a visible
"pending" marker so the manuscript compiles and nothing is silently invented.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from _manifests import REPO, artifact_json, latest_runs

PENDING = r"\textcolor{red}{[pending]}"


def fmt(x, nd=3):
    return PENDING if x is None else f"{x:.{nd}f}"


def build(root: Path, citable: bool) -> tuple[str, str]:
    runs = latest_runs(root, citable)
    macros: dict[str, str] = {}
    sources: list[str] = []

    def get(tool, cfg):
        r = runs.get((tool, cfg))
        if r:
            sources.append(f"{tool}/{r[1]['run_id']} @ {r[1]['git']['sha'][:10]}")
        return r

    r = get("metric_selfcheck", "metric_selfcheck")
    res = r[1]["results"] if r else {}
    diff = res.get("max_abs_diff_vs_official", {})
    macros["MetricMaxDiffAUPRO"] = PENDING if not diff else f"{diff['au_pro']:.1e}"
    macros["MetricMaxDiffAUROC"] = PENDING if not diff else f"{diff['image_auroc']:.1e}"

    r = get("profile_data", "phase0_data")
    tot = r[1]["results"]["totals"] if r else {}
    for k, name in (("images", "DatasetNumImages"), ("train_good", "DatasetNumTrain"),
                    ("test_good", "DatasetNumTestGood"), ("test_defect", "DatasetNumTestDefect")):
        macros[name] = str(tot[k]) if k in tot else PENDING
    macros["DatasetErasedByPolicy"] = str(r[1]["results"]["n_erased_by_policy"]) if r else PENDING
    summary = artifact_json(r[0], r[1], "profile_summary.json") if r else None

    r = get("evaluator_sanity", "evaluator_sanity")
    res = r[1]["results"] if r else {}
    for kind, name in (("constant", "Constant"), ("random", "Random"), ("oracle_mask", "Oracle")):
        for metric, mname in (("image_auroc", "ImgAUROC"), ("pixel_auroc", "PixAUROC"), ("au_pro", "AUPRO")):
            macros[f"Sanity{name}{mname}"] = fmt(res.get(kind, {}).get(metric))

    lines = ["% AUTO-GENERATED by scripts/make_tables.py from manifests. DO NOT EDIT.",
             "% sources: " + ("; ".join(sources) if sources else "none yet"),
             r"\providecommand{\textcolor}[2]{#2}"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(macros.items())]

    rows = ["% AUTO-GENERATED by scripts/make_tables.py. DO NOT EDIT."]
    if summary:
        cats = summary["categories"]
        area = summary["per_category_defect_area"]
        for c in sorted(cats):
            d = cats[c]
            a = area.get(c, {})
            med = f"{100 * a['median']:.2f}" if a else "--"
            rows.append(f"{c.replace('_', ' ')} & {d['train_good']} & {d['test_good']} & {d['test_defect']} & "
                        f"{len(d['defect_types'])} & {med} \\\\")
    else:
        rows.append(PENDING + r" & & & & & \\")
    table = [rows[0], r"\begin{tabular}{lrrrrr}", r"\toprule",
             r"Category & Train & Test good & Test defect & Types & Median area (\%) \\", r"\midrule",
             *rows[1:], r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n", "\n".join(table) + "\n"


def main(argv=None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--manifest-root", default=str(REPO / "results" / "manifests"))
    p.add_argument("--out", default=str(REPO / "paper" / "generated"))
    p.add_argument("--citable", action="store_true", help="refuse dirty/unknown-git manifests")
    a = p.parse_args(argv)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    macros, table = build(Path(a.manifest_root), a.citable)
    (out / "results_macros.tex").write_text(macros)
    (out / "table_dataset.tex").write_text(table)
    print(f"wrote {out / 'results_macros.tex'} and {out / 'table_dataset.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
